import { readFileSync } from "fs";
import path from "path";

import { uploadImageBuffer } from "../lib/uploads/image-storage.server";

async function main() {
  const pngBytes = Buffer.from([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
    0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1f,
    0x15, 0xc4, 0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x00,
    0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0d, 0x0a, 0x2d, 0xb4, 0x00, 0x00, 0x00, 0x00, 0x49,
    0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82,
  ]);

  const uploaded = await uploadImageBuffer(pngBytes, "comment", "image/png");
  const filePath = path.join(process.cwd(), "public", uploaded.url.replace(/^\//, ""));

  if (!readFileSync(filePath)) {
    throw new Error("Uploaded file was not written to disk.");
  }

  console.log("Local upload OK:", uploaded.url);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
